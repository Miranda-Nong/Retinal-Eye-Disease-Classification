import numpy as np
import os
import matplotlib.pyplot as plt
import tensorflow as tf

from tensorflow.keras.applications import VGG16
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D
from tensorflow.keras.models import Model
from tensorflow.keras.optimizers import Adam
from tensorflow.keras.callbacks import EarlyStopping
from sklearn.metrics import confusion_matrix, ConfusionMatrixDisplay
from sklearn.metrics import classification_report, accuracy_score
from tensorflow.keras import layers

import warnings
warnings.filterwarnings('ignore')

from google.colab import drive
drive.mount('/content/drive')

train_dir = '/content/drive/MyDrive/dataset'

print("Dataset path:", train_dir)
print("Classes:", os.listdir(train_dir))

train_ds = tf.keras.preprocessing.image_dataset_from_directory(
    train_dir,
    validation_split=0.2,
    subset='training',
    batch_size=32,
    image_size=(224, 224),
    seed=123,
    shuffle=True
)

val_ds = tf.keras.preprocessing.image_dataset_from_directory(
    train_dir,
    validation_split=0.2,
    subset='validation',
    batch_size=32,
    image_size=(224, 224),
    seed=123,
    shuffle=True
)

class_names = train_ds.class_names

print("Class Names:", class_names)

num_classes = len(class_names)

print("Number of Classes:", num_classes)

import random
from PIL import Image

def visualize_images(path, target_size=(256, 256), num_images=5):

    image_filenames = [
        f for f in os.listdir(path)
        if os.path.isfile(os.path.join(path, f))
    ]

    if not image_filenames:
        raise ValueError("No images found in the specified path")

    selected_images = random.sample(
        image_filenames,
        min(num_images, len(image_filenames))
    )

    fig, axes = plt.subplots(
        1,
        len(selected_images),
        figsize=(15, 3),
        facecolor='white'
    )

    if len(selected_images) == 1:
        axes = [axes]

    for i, image_filename in enumerate(selected_images):

        image_path = os.path.join(path, image_filename)

        image = Image.open(image_path)
        image = image.resize(target_size)

        axes[i].imshow(image)
        axes[i].axis('off')
        axes[i].set_title(image_filename)

    plt.tight_layout()
    plt.show()

path_to_visualize = "/content/drive/MyDrive/dataset/cataract"
